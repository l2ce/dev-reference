import type { Collection } from '@l2ce/database'

/**
 * Один аргумент зарегистрированного параметра и его публичная семантика.
 */
export type HelpOption = {
  /** Сигнатура Commander, используемая также при регистрации. */
  flags: string
  /** Смысл параметра, а не повтор его имени. */
  description: string
  /** Тип принимаемого значения. */
  valueType: string
  /** Семантическое умолчание, включая отсутствие изменения. */
  defaultDescription: string
  /** Допустимые значения перечисления. */
  choices?: string[]
  /** Фактическое значение по умолчанию для парсера. */
  defaultValue?: string | boolean
  /** Способ разбора и накопления значения. */
  parser?: 'positive' | 'nonnegative' | 'repeat'
  /** Обязательный флаг независимо от других способов ввода. */
  required?: boolean
  /** Поле предметного ввода для контекстной фильтрации. */
  field?: string
  /** Дополнительное ограничение или пример формата. */
  rules: string[]
  /** Совместимый, но не рекомендуемый новый ввод. */
  legacy?: boolean
}

/**
 * Правило с устойчивым именем для справки, диагностики и проверки покрытия.
 */
export type HelpRule = {
  /** Устойчивый идентификатор правила. */
  id: string
  /** Полное объяснение ограничения или гарантии. */
  text: string
}

/**
 * Выполняемый шаг примера; stdin остаётся буквальными данными.
 */
export type ExampleStep = {
  /** Аргументы без имени executable и без пути тестовой базы. */
  args: string[]
  /** Буквальное содержимое stdin. */
  stdin?: string
  /** Ожидаемый код завершения; по умолчанию успех. */
  exitCode?: number
  /** Сохранить показанную версию для последующего <version>. */
  captureVersion?: boolean
  /** Сохранить курсор страницы для последующего <cursor>. */
  captureCursor?: boolean
  /** Ожидаемый буквальный результат --content. */
  content?: string
  /** Проверяемые JSON-пути результата; <version>/<cursor> заменяются полученными токенами. */
  expect?: Record<string, unknown>
}

/**
 * Самодостаточный пример, используемый рендерером и исполняемыми тестами.
 */
export type HelpExample = {
  /** Устойчивое имя сценария внутри команды. */
  id: string
  /** Что демонстрирует пример. */
  title: string
  /** Объяснение предусловий и подстановок. */
  preconditions: string[]
  /** Команды подготовки из пустой изолированной базы. */
  setup: ExampleStep[]
  /** Полные UTF-8 файлы для варианта с существующим файлом. */
  files?: Record<string, string>
  /** Основные команды примера. */
  steps: ExampleStep[]
  /** Что должен увидеть пользователь и что проверяет сценарий. */
  expected: string[]
}

/**
 * Декларативный контракт команды; регистрация и справка используют одну запись.
 */
export type CommandSpec = {
  /** Путь команды с точками между уровнями. */
  id: string
  /** Сигнатура последнего уровня, включая позиционные аргументы. */
  signature: string
  /** Назначение команды или группы. */
  purpose: string
  /** Описание каждого позиционного аргумента по имени. */
  arguments: Record<string, string>
  /** Идентификаторы параметров единого реестра. */
  options: string[]
  /** Флаги, обязательные независимо от каналов передачи предметных значений. */
  requiredOptions?: string[]
  /** Полное описание сложного предметного ввода, не помещающееся в подпись одного параметра. */
  details?: string[]
  /** Группа без собственного предметного действия. */
  group?: boolean
  /** Определение типа из адреса или --type. */
  typed?: boolean
  /** Схема полей, если имя операции отличается от пути команды. */
  fieldsOperation?: string
  /** Общие наборы правил, применимые к этой команде. */
  ruleSets: string[]
  /** Собственные предметные правила. */
  rules: HelpRule[]
  /** Содержимое результата и его область. */
  result: string
  /** Отсутствующие значения, повтор и no-op. */
  absence: string
  /** Операции, полезные после текущей. */
  related: string[]
}

/**
 * Явный контекст справки без обращения к базе.
 */
export type HelpContext = {
  /** Явно выбранная база для команд восстановления, не для изолированных примеров. */
  database?: string
  /** Явно выбранный язык исходного запроса. */
  locale?: string
  /** Все существующие переводы вместо одного языка. */
  allLocales?: boolean
  /** Формат результата команд восстановления. */
  format?: 'text' | 'json'
  /** Тип записи, определённый из адреса или --type. */
  collection?: Collection
  /** Необязательный адрес, не требующий существования записи. */
  key?: string
  /** Несколько явно выбранных типов для смешанного чтения. */
  collections?: Collection[]
  /** Явно переданный протокол уточняет поля знания, но не требует открытия базы. */
  protocol?: string
}

/**
 * Ошибка и готовый безопасный следующий шаг.
 */
export type HelpError = {
  /** Стабильный машинный код. */
  code: string
  /** Понятная причина ошибки. */
  reason: string
  /** Команда или действие для исправления, без автоматического повтора записи. */
  recovery: string
}
